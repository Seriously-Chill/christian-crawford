/**
 * The site's mark: two shapes, a large rounded body and a smaller crescent
 * beside it. Drawn inline (not as an <img> or CSS mask) so each shape is
 * its own element — `[data-logo-part="body"]` and `[data-logo-part="accent"]`
 * — ready to animate independently. Fills with `currentColor`, so the
 * mark takes the surrounding text color and follows the color picker.
 *
 * Traced from the 190×166 source artwork, with the crescent moved 14 units
 * further from the body for more separation; `public/logo-mark.svg` is the
 * same drawing as a standalone file.
 */
export function LogoMark({
  className = "",
  fluid = false,
  ref,
}: {
  className?: string;
  /** Adds idle `<animate>`s that morph each shape; FluidLogoMark starts them. */
  fluid?: boolean;
  ref?: Ref<SVGSVGElement>;
}) {
  return (
    <svg
      ref={ref}
      viewBox="0 0 204 167"
      aria-hidden="true"
      focusable="false"
      className={className}
      fill="currentColor"
      // The warped shapes swell a few units past the viewBox; don't clip them.
      overflow={fluid ? "visible" : undefined}
    >
      <path data-logo-part="body" d={BODY_PATH}>
        {fluid && <Morph values={[BODY_PATH, BODY_WARP_A, BODY_WARP_B, BODY_PATH]} />}
      </path>
      <path data-logo-part="accent" d={ACCENT_PATH}>
        {fluid && <Morph values={[ACCENT_PATH, ACCENT_WARP_B, ACCENT_WARP_A, ACCENT_PATH]} />}
      </path>
    </svg>
  );
}

/** Morph cycle length, shared by both shapes so their cycles end together. */
const LOGO_MORPH_MS = 2400;

/**
 * SMIL rather than CSS `d` keyframes: Safari doesn't animate the CSS `d`
 * property. `begin="indefinite"` keeps it idle until script calls
 * beginElement(), so nothing moves without JS or for reduced-motion users.
 * Each cycle starts and ends on the true shape, so stopping at a cycle
 * boundary never snaps.
 */
function Morph({ values }: { values: string[] }) {
  return (
    <animate
      attributeName="d"
      dur={`${LOGO_MORPH_MS}ms`}
      begin="indefinite"
      repeatCount="indefinite"
      calcMode="spline"
      keyTimes="0;0.35;0.7;1"
      keySplines="0.45 0 0.55 1;0.45 0 0.55 1;0.45 0 0.55 1"
      values={values.join(";")}
    />
  );
}
